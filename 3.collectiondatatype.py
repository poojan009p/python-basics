"---List---" # All the numbers excluding decimal places and fraction

number = [1,2,3,4,5,6,7,8,9] # syntax[]
                             # Mutable,Duplicates,Ordered,Heterogenous

#-----------------------------------------------------------------------------------------------------------------------------------"

"---Tuple---" # All the numbers excluding decimal places and fraction

number = (1,2,3,4,5,6,7,8,9) # syntax()
                             # Immutable,Duplicates,Ordered,Heterogenous

#-----------------------------------------------------------------------------------------------------------------------------------"

"---Set---" # All the numbers excluding decimal places and fraction

number = {1,2,3,4,5,6,7,8,9} # syntax{}
                             # Immutable,Duplicates,Unordered,Heterogenous

#-----------------------------------------------------------------------------------------------------------------------------------"

"---Dictionary---" # Stores data as key-value pairs.

person = {"name": "Poojan",} # syntax
                             # Mutable,Duplicates,Ordered,Heterogenous
print(person["name"])


