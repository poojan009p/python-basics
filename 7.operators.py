"--------------------------------------------------------------------------------------------" 
"---Arithmetic operators---"

# Arithmetic operators perform mathematical operations like 
# addition, subtraction, multiplication, division, etc

# there are total 7 types of arithmetic operators

"""
addition        - +
substraction    - -
multiplication  - *
division        - /
floor division  - //
modulus         - %
exponential     - **
"""

a=9
b=9

print(a+b)
print(a-b)
print(a*b)
print(a/b)
print(a//b)
print(a**b)
print(a%b)

