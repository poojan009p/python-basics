"--------------------------------------------------------------"
"---String Indexing---"

name = "poojan"

print(name[0])  #p
print(name[1])  #o
print(name[2])  #o      # Positive indexing starts from 0
print(name[-3]) #j      # Negative indexing starts from -1
print(name[-2]) #a  
print(name[-1]) #n

"--------------------------------------------------------------"
